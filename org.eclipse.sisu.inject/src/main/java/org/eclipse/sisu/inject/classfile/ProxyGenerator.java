package org.eclipse.sisu.inject.classfile;

import javax.inject.Provider;

/**
 * Generates small synthetic proxy classes.
 *
 * <p>
 * This is an internal Sisu SPI, not a public API: implementations are selected
 * at runtime by {@link ClassFileSupport}.
 *
 * <p>
 * The provider proxy generated by {@link #generateProviderProxy(String, Class)}
 * is a {@code public final} class with a single {@code public} constructor
 * accepting a {@link Provider}: if the facade is an interface, the proxy
 * implements it; otherwise the proxy extends the facade class and implements
 * its interfaces. All wrappable public methods of the facade are overridden to
 * delegate to the provider's target: non-{@code Object} methods throw
 * {@link IllegalStateException} if the target is {@code null}, while
 * {@code Object} methods (except {@code toString}) fall back to the superclass
 * implementation.
 */
public interface ProxyGenerator {
    // ----------------------------------------------------------------------
    // Constants
    // ----------------------------------------------------------------------

    /**
     * Field name of the generated provider proxy that stores the provider handle.
     */
    String PROVIDER_HANDLE = "__sisu__";

    // ----------------------------------------------------------------------
    // Operations
    // ----------------------------------------------------------------------

    /**
     * Generates a {@code public} subclass of the given superclass whose no-arg
     * constructor delegates to the superclass' no-arg constructor.
     *
     * @param proxyName The internal name (slash-separated) of the clone class
     * @param superName The internal name (slash-separated) of the clone's superclass
     * @return The class file bytes
     */
    byte[] generateClone(String proxyName, String superName);

    /**
     * Generates a dynamic {@link Provider}-based proxy that reflects the given facade.
     *
     * @param proxyName The internal name (slash-separated) of the proxy class
     * @param facade The facade to reflect
     * @return The class file bytes
     */
    byte[] generateProviderProxy(String proxyName, Class<?> facade);
}
